// Initialize i18n
const i18n = {
  currentLang: localStorage.getItem('mw_lang') || 'en',
  
  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem('mw_lang', lang);
      this.render();
    }
  },
  
  t(key) {
    return translations[this.currentLang]?.[key] || translations.en[key] || key;
  },
  
  render() {
    // Update all elements with data-i18n attribute (for text content)
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) {
          el.placeholder = text;
        } else {
          el.value = text;
        }
      } else {
        el.textContent = text;
      }
    });

    // Update all elements with data-i18n-placeholder attribute (for placeholders)
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      }
    });

    // Update elements with id matching translation keys (legacy support)
    Object.keys(translations[this.currentLang]).forEach(key => {
      const el = document.getElementById(key);
      if (el) {
        if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
          el.placeholder = this.t(key);
        } else {
          el.textContent = this.t(key);
        }
      }
    });
  }
};

// Initialize on load
document.addEventListener('DOMContentLoaded', () => {
  i18n.render();
  const langSelect = document.getElementById('lang-select');
  if (langSelect) {
    langSelect.value = i18n.currentLang;
    langSelect.addEventListener('change', (e) => i18n.setLanguage(e.target.value));
  }
});

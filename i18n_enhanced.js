// Enhanced i18n with auto-detection
const i18n = {
  currentLang: null,
  
  init() {
    // Try to get saved language
    let savedLang = localStorage.getItem('mw_lang');
    
    // If no saved language, detect from browser
    if (!savedLang) {
      const browserLang = navigator.language || navigator.userLanguage;
      savedLang = this.detectLanguage(browserLang);
    }
    
    this.currentLang = savedLang;
    return this;
  },
  
  detectLanguage(browserLang) {
    // Map browser language codes to our supported languages
    const langMap = {
      'en': 'en', 'en-US': 'en', 'en-GB': 'en',
      'es': 'es', 'es-ES': 'es', 'es-MX': 'es',
      'fr': 'fr', 'fr-FR': 'fr', 'fr-CA': 'fr',
      'de': 'de', 'de-DE': 'de',
      'it': 'it', 'it-IT': 'it',
      'pt': 'pt', 'pt-BR': 'pt', 'pt-PT': 'pt',
      'ar': 'ar', 'ar-SA': 'ar', 'ar-EG': 'ar',
      'ja': 'ja', 'ja-JP': 'ja',
      'ko': 'ko', 'ko-KR': 'ko',
      'zh': 'zh-cn', 'zh-CN': 'zh-cn', 'zh-SG': 'zh-cn', 'zh-Hans': 'zh-cn',
      'zh-TW': 'zh-tw', 'zh-HK': 'zh-tw', 'zh-MO': 'zh-tw', 'zh-Hant': 'zh-tw',
      'hi': 'hi', 'hi-IN': 'hi',
      'ru': 'ru', 'ru-RU': 'ru',
      'nl': 'nl', 'nl-NL': 'nl'
    };
    
    // Check if we have exact match
    if (langMap[browserLang]) {
      return langMap[browserLang];
    }
    
    // Check if we have language prefix match (e.g., 'en' from 'en-AU')
    const langPrefix = browserLang.split('-')[0];
    if (langMap[langPrefix]) {
      return langMap[langPrefix];
    }
    
    // Default to English
    return 'en';
  },
  
  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem('mw_lang', lang);
      this.render();
      
      // Update document direction for RTL languages
      if (lang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
        document.documentElement.setAttribute('lang', 'ar');
      } else {
        document.documentElement.setAttribute('dir', 'ltr');
        document.documentElement.setAttribute('lang', lang);
      }
    }
  },
  
  t(key) {
    return translations[this.currentLang]?.[key] || translations.en[key] || key;
  },
  
  render() {
    // Update all elements with data-i18n attribute (for text content)
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) {
          el.placeholder = text;
        } else {
          el.value = text;
        }
      } else {
        el.textContent = text;
      }
    });
    
    // Update all elements with data-i18n-placeholder attribute (for placeholders)
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', this.t(key));
    });
    
    // Update elements with id matching translation keys (legacy support)
    Object.keys(translations[this.currentLang] || translations.en).forEach(key => {
      const el = document.getElementById(key);
      if (el) {
        if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
          el.placeholder = this.t(key);
        } else {
          el.textContent = this.t(key);
        }
      }
    });

    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      window.dispatchEvent(new CustomEvent('i18n:rendered', {
        detail: { lang: this.currentLang }
      }));
    }

    return this;
  }
};

// Auto-initialize
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    i18n.init().render();
  });
} else {
  i18n.init().render();
}

// Set up language selector after i18n is initialized
window.addEventListener('load', () => {
  const langSelect = document.getElementById('lang-select') || document.querySelector('select[name="language"]');
  if (langSelect && !langSelect.hasAttribute('data-i18n-initialized')) {
    langSelect.setAttribute('data-i18n-initialized', 'true');
    langSelect.value = i18n.currentLang;
    langSelect.addEventListener('change', (e) => {
      i18n.setLanguage(e.target.value);
    });
  }
});

